const GENERATED_NOTE = "<!-- Generated by opencode-memory. Edits to this file are overwritten. -->"

export function forgottenTopicLabel(topicId: string): string {
  const short = topicId.replace(/^topic_/, "").slice(0, 8)
  return `Forgotten topic ${short}`
}

export function forgottenTopicSlug(topicId: string): string {
  return `forgotten-${topicId.replace(/^topic_/, "").slice(0, 8)}`
}

/** Same folder as the current file (old layouts keep working links), new file name. */
export function relPathWithSlug(relPath: string, slug: string): string {
  const i = relPath.lastIndexOf("/")
  return `${i < 0 ? "" : relPath.slice(0, i + 1)}${slug}.md`
}

export function scopeDir(db: Database, scopeKey: string): string {
  const [kind, id] = scopeKey.split(":")
  if (kind === "workspace") return slugify(id) || "workspace"
  if (kind === "project") {
    const p = db.prepare("SELECT workspace, name FROM projects WHERE id = ?").get<{ workspace: string; name: string | null }>(id)
    const slug = slugify(p?.name ?? id) || "project"
    const tag = (id.replace(/[^a-zA-Z0-9]/g, "").slice(-8) || sha256(id).slice(0, 8)).toLowerCase()
    return join(slugify(p?.workspace ?? "workspace"), "projects", `${slug}-${tag}`)
  }
  return "user"
}

export function topicRelPath(db: Database, scopeKey: string, slug: string): string {
  return join(scopeDir(db, scopeKey), "topics", `${slug}.md`).split(sep).join("/")
}

type LiveRef = { id: string; status: string; visibility: string; superseded_by: string | null; scope_kind: string; project_id: string | null; workspace: string }

function liveRefRow(db: Database, id: string): LiveRef | null {
  const seen = new Set<string>()
  let cur: string | null = id
  while (cur && !seen.has(cur)) {
    seen.add(cur)
    const currentId: string = cur
    if (isIdSuppressed(db, currentId)) return null
    const row: LiveRef | undefined = db
      .prepare("SELECT id, status, visibility, superseded_by, scope_kind, project_id, workspace FROM observations WHERE id = ?")
      .get<LiveRef>(currentId)
    if (!row || row.visibility !== "visible") return null
    if (row.status === "forgotten") return null
    if (row.status === "active" || row.status === "pending_review") return row
    if (row.status === "superseded" && row.superseded_by) {
      const next = db.prepare("SELECT kind FROM observations WHERE id = ?").get<{ kind: string }>(row.superseded_by)
      if (next?.kind !== "condensed") return null
      cur = row.superseded_by
      continue
    }
    return null
  }
  return null
}

/**
 * Follow a condense link to the live summary that absorbed the evidence. A plain
 * supersede means the bullet is outdated (not re-pinned to the successor); forgotten
 * or missing rows return null.
 */
export function resolveLiveRef(db: Database, id: string): string | null {
  return liveRefRow(db, id)?.id ?? null
}

/** A topic may only cite observations readable from its own scope. */
function readableFromTopic(row: Pick<LiveRef, "scope_kind" | "project_id" | "workspace">, target: SuppressionTarget): boolean {
  if (row.scope_kind === "user") return true
  if (row.scope_kind === "workspace") return target.scope_kind !== "user" && row.workspace === target.workspace
  return target.scope_kind === "project" && !!row.project_id && row.project_id === target.project_id
}

function projectBullet(db: Database, b: { text: string; refs: string[] }, target?: SuppressionTarget): { text: string; refs: string[] } | null {
  if (isSuppressed(db, b.text, target)) return null
  if (!b.refs.length) return { text: b.text, refs: [] }
  const resolved: string[] = []
  for (const r of b.refs) {
    const live = liveRefRow(db, r)
    if (!live || (target && !readableFromTopic(live, target))) return null
    resolved.push(live.id)
  }
  return { text: b.text, refs: [...new Set(resolved)] }
}

/** Suppressed headings lose their text, not their (still valid) bullets. */
function headingOf(db: Database, heading: string, target?: SuppressionTarget): string {
  return isSuppressed(db, heading, target) ? "Notes" : heading
}

/** Deterministic Markdown body. Every generated bullet line carries its observation refs so forget can strip it. */
export function renderTopicBody(title: string, summary: string, sections: TopicSection[], preamble: string[] = []): string {
  const out = [`# ${title}`, ""]
  if (summary) out.push(`> ${summary}`, "")
  for (const line of preamble) if (line.trim()) out.push(line)
  if (preamble.some((l) => l.trim())) out.push("")
  for (const s of sections) {
    out.push(`## ${s.heading}`, "")
    for (const extra of s.extras ?? []) if (extra.trim()) out.push(extra)
    for (const b of s.bullets) {
      const text = b.text.replace(/\s+/g, " ").trim()
      out.push(b.refs.length ? `- ${text} — refs: ${b.refs.join(", ")}` : `- ${text}`)
    }
    out.push("")
  }
  return out.join("\n").trimEnd() + "\n"
}

/** Inverse of renderTopicBody. Unknown lines and ref-less bullets are preserved for external edits. */
export function parseTopicBody(body: string): { title: string; summary: string; sections: TopicSection[]; preamble: string[] } {
  let title = ""
  let summary = ""
  const preamble: string[] = []
  const sections: TopicSection[] = []
  for (const raw of body.replace(/\r\n/g, "\n").split("\n")) {
    const line = raw.trimEnd()
    if (!line.trim() || line.startsWith("<!--")) continue
    if (line.startsWith("# ") && !title) title = line.slice(2).trim()
    else if (line.startsWith("> ") && !sections.length) summary = line.slice(2).trim()
    else if (line.startsWith("## ")) sections.push({ heading: line.slice(3).trim(), bullets: [], extras: [] })
    else if (line.startsWith("- ") && sections.length) {
      const m = line.slice(2).match(/^(.*?)(?: — refs: (.*))?$/)
      const refs = (m?.[2] ?? "")
        .split(",")
        .map((r) => r.trim())
        .filter(Boolean)
      sections[sections.length - 1].bullets.push({ text: (m?.[1] ?? line.slice(2)).trim(), refs })
    } else if (sections.length) {
      sections[sections.length - 1].extras = [...(sections[sections.length - 1].extras ?? []), line]
    } else if (title) {
      preamble.push(line)
    }
  }
  return { title, summary, sections, preamble }
}

/**
 * Merge new sections into an existing topic: sections the op omits are kept,
 * sections it names get the new bullets plus old bullets that are not
 * near-duplicates. Forgotten refs drop the bullet; condensed evidence is rewritten
 * to the live successor. Ref-less bullets (user-written) are kept.
 */
export function mergeTopicSections(db: Database, existing: TopicSection[], incoming: TopicSection[], target?: SuppressionTarget): TopicSection[] {
  const key = (h: string) => h.trim().toLowerCase()
  const byHeading = new Map(incoming.map((s) => [key(s.heading), s]))
  const out: TopicSection[] = []
  const seen = new Set<string>()
  for (const old of existing) {
    const k = key(old.heading)
    const fresh = byHeading.get(k)
    if (!fresh) {
      out.push(old)
      continue
    }
    seen.add(k)
    const kept = old.bullets.filter((b) => !fresh.bullets.some((n) => jaccard(shingles(n.text), shingles(b.text)) >= 0.6))
    const extras = [...(fresh.extras ?? []), ...(old.extras ?? []).filter((e) => !(fresh.extras ?? []).includes(e))]
    out.push({ heading: fresh.heading, bullets: [...fresh.bullets, ...kept], extras: extras.length ? extras : undefined })
  }
  for (const s of incoming) if (!seen.has(key(s.heading))) out.push(s)
  return out
    .map((s) => ({
      heading: headingOf(db, s.heading, target),
      extras: (s.extras ?? []).filter((e) => e.trim() && !isSuppressed(db, e, target)),
      bullets: s.bullets.map((b) => projectBullet(db, b, target)).filter((b): b is { text: string; refs: string[] } => !!b),
    }))
    .filter((s) => s.bullets.length || (s.extras && s.extras.length))
}

function frontMatter(fields: Record<string, string | number>): string {
  return ["---", ...Object.entries(fields).map(([k, v]) => `${k}: ${typeof v === "string" ? JSON.stringify(v) : v}`), "---", ""].join("\n")
}

export function parseFile(text: string): { fields: Record<string, string>; body: string } {
  const m = text.match(/^---\r?\n([\s\S]*?)\r?\n---\r?\n?/)
  if (!m) return { fields: {}, body: text }
  const fields: Record<string, string> = {}
  for (const line of m[1].split(/\r?\n/)) {
    const i = line.indexOf(":")
    if (i < 0) continue
    const k = line.slice(0, i).trim()
    let v = line.slice(i + 1).trim()
    if (v.startsWith('"')) {
      try {
        v = JSON.parse(v)
      } catch {}
    }
    fields[k] = v
  }
  return { fields, body: text.slice(m[0].length) }
}

function bodyHash(body: string): string {
  return sha256(body.replace(/\r\n/g, "\n"))
}

function refsOfLine(line: string): string[] {
  const m = line.match(/refs:\s*(.+)$/i)
  if (!m) return []
  return m[1]
    .split(",")
    .map((r) => r.trim())
    .filter(Boolean)
}

function lineCitesDeadRef(db: Database, line: string, target?: SuppressionTarget): boolean {
  const refs = refsOfLine(line)
  if (
    refs.some((id) => {
      const live = liveRefRow(db, id)
      return !live || (!!target && !readableFromTopic(live, target))
    })
  )
    return true
  const obsIds = line.match(/\bobs_[a-zA-Z0-9]+/g) ?? []
  return obsIds.some((id) => {
    if (isIdSuppressed(db, id)) return true
    const row = getObservation(db, id)
    return !!row && (row.status === "forgotten" || (!!target && !readableFromTopic(row, target)))
  })
}

/**
 * Remove forgotten/unknown refs, refs not readable from the topic's scope, suppressed
 * lines (title, summary, headings, bullets, free text), and secrets from a vault body.
 */
export function sanitizeTopicBody(db: Database, body: string, target?: SuppressionTarget, fallbackTitle = "Topic"): string {
  const redacted = redact(body.replace(/\r\n/g, "\n")).text
  const parsed = parseTopicBody(redacted)
  const sup = (text: string) => isSuppressed(db, text, target)
  const title = parsed.title && !sup(parsed.title) ? parsed.title : fallbackTitle
  let summary = parsed.summary
  if (summary && (sup(summary) || lineCitesDeadRef(db, summary, target))) summary = ""
  const preamble = parsed.preamble.filter((l) => l.trim() && !sup(l) && !lineCitesDeadRef(db, l, target))
  const sections = parsed.sections
    .map((s) => ({
      heading: headingOf(db, s.heading, target),
      extras: (s.extras ?? []).filter((e) => e.trim() && !sup(e) && !lineCitesDeadRef(db, e, target)),
      bullets: s.bullets.map((b) => projectBullet(db, b, target)).filter((b): b is { text: string; refs: string[] } => !!b),
    }))
    .filter((s) => s.bullets.length || s.extras.length)
  return renderTopicBody(title, summary, sections, preamble)
}

/** A forgotten title must not survive in the file name or INDEX link either. */
function storedSlug(db: Database, id: string, slug: string, title: string, target?: SuppressionTarget): string {
  return title === forgottenTopicLabel(id) || isSuppressed(db, slug.replace(/-/g, " "), target) ? forgottenTopicSlug(id) : slug
}

export function upsertTopic(
  db: Database,
  input: { scopeKey: string; slug: string; title: string; summary: string; sections: TopicSection[]; actor: string; merge?: boolean },
  now = Date.now(),
): { id: string; generation: number; changed: boolean } {
  return db.tx(() => upsertTopicInternal(db, input, now))
}

function upsertTopicInternal(
  db: Database,
  input: { scopeKey: string; slug: string; title: string; summary: string; sections: TopicSection[]; actor: string; merge?: boolean },
  now: number,
): { id: string; generation: number; changed: boolean } {
  const slug = slugify(input.slug) || slugify(input.title)
  const id = `topic_${sha256(`${input.scopeKey}\u0000${slug}`).slice(0, 16)}`
  const target = suppressionTarget(db, input.scopeKey)
  const existing = db.prepare("SELECT * FROM topics WHERE id = ?").get<TopicRow>(id)
  let sections = input.sections
  let summary = input.summary
  let preamble: string[] = []
  if (input.merge && existing) {
    const prev = parseTopicBody(existing.body)
    sections = mergeTopicSections(db, prev.sections, input.sections, target)
    summary = input.summary.trim() || existing.summary || ""
    preamble = prev.preamble
  }
  if (isSuppressed(db, summary, target)) summary = ""
  let title = input.title
  if (isSuppressed(db, title, target)) title = forgottenTopicLabel(id)
  const body = sanitizeTopicBody(db, renderTopicBody(title, summary, sections, preamble), target, forgottenTopicLabel(id))
  const parsed = parseTopicBody(body)
  title = parsed.title || title
  summary = parsed.summary
  const finalSlug = storedSlug(db, id, slug, title, target)
  const relPath = existing
    ? finalSlug === existing.slug
      ? existing.rel_path
      : relPathWithSlug(existing.rel_path, finalSlug)
    : topicRelPath(db, input.scopeKey, finalSlug)
  const hash = contentHash(body)
  if (existing && existing.content_hash === hash && relPath === existing.rel_path) return { id, generation: existing.generation, changed: false }
  const generation = (existing?.generation ?? 0) + 1
  if (existing) {
    if (relPath !== existing.rel_path) enqueueVaultDelete(db, existing.rel_path, now)
    db.prepare(
      `UPDATE topics SET slug = ?, rel_path = ?, title = ?, summary = ?, body = ?, generation = ?, content_hash = ?, approved = 0,
         state = CASE WHEN state = 'conflict' THEN 'conflict' ELSE 'active' END, updated_at = ? WHERE id = ?`,
    ).run(finalSlug, relPath, title, summary, body, generation, hash, now, id)
  } else {
    db.prepare(
      `INSERT INTO topics(id, scope_key, slug, rel_path, title, summary, body, generation, content_hash, state, approved, updated_at)
       VALUES (?,?,?,?,?,?,?,?,?, 'active', 0, ?)`,
    ).run(id, input.scopeKey, finalSlug, relPath, title, summary, body, generation, hash, now)
  }
  db.prepare("INSERT INTO topic_generations(topic_id, generation, title, body, hash, actor, created_at) VALUES (?,?,?,?,?,?,?)").run(
    id,
    generation,
    title,
    body,
    hash,
    input.actor,
    now,
  )
  enqueueTopic(db, id, now)
  bumpMemoryGeneration(db)
  return { id, generation, changed: true }
}

/**
 * Queue the file write in the same transaction as the topic generation.
 * force overwrites an externally edited file (used by forget, which must not leave content on disk).
 */
export function enqueueTopic(db: Database, topicId: string, now = Date.now(), force = false) {
  const t = db.prepare("SELECT * FROM topics WHERE id = ?").get<TopicRow>(topicId)
  if (!t) return
  db.prepare("UPDATE vault_outbox SET state = 'superseded' WHERE topic_id = ? AND state IN ('pending','conflict')").run(topicId)
  db.prepare("UPDATE vault_outbox SET state = 'superseded' WHERE rel_path = ? AND content = '' AND state = 'pending'").run(t.rel_path)
  const file =
    frontMatter({ om_id: t.id, om_generation: t.generation, om_hash: bodyHash(t.body), title: t.title, updated: new Date(now).toISOString() }) + t.body
  db.prepare("INSERT INTO vault_outbox(rel_path, topic_id, generation, content, hash, state, force, created_at) VALUES (?,?,?,?,?, 'pending', ?, ?)").run(
    t.rel_path,
    t.id,
    t.generation,
    file,
    bodyHash(t.body),
    force ? 1 : 0,
    now,
  )
}

/** Queue deletion of a vault path (empty content + force). */
export function enqueueVaultDelete(db: Database, relPath: string, now = Date.now()) {
  db.prepare("UPDATE vault_outbox SET state = 'superseded' WHERE rel_path = ? AND state IN ('pending','conflict')").run(relPath)
  db.prepare("INSERT INTO vault_outbox(rel_path, topic_id, generation, content, hash, state, force, created_at) VALUES (?, NULL, NULL, '', ?, 'pending', 1, ?)").run(
    relPath,
    sha256(""),
    now,
  )
}

export function regenerateIndexes(db: Database, workspace: string, now = Date.now()) {
  const root = slugify(workspace) || "workspace"
  const topics = db
    .prepare("SELECT * FROM topics WHERE state != 'deleted' ORDER BY scope_key, title")
    .all<TopicRow>()
    .filter((t) => t.rel_path.startsWith(`${root}/`))
  const index = [
    GENERATED_NOTE,
    `# ${workspace} — memory index`,
    "",
    ...topics.map((t) => `- [${t.title}](${relative(root, t.rel_path).split(sep).join("/")})${t.summary ? ` — ${t.summary}` : ""}`),
    "",
  ].join("\n")
  const projectKeys = db
    .prepare("SELECT id FROM projects WHERE workspace = ?")
    .all<{ id: string }>(workspace)
    .map((p) => `project:${p.id}`)
  const keys = [`workspace:${workspace}`, ...projectKeys]
  const journey = db
    .prepare(`SELECT at, entry FROM journey_entries WHERE scope_key IN (${keys.map(() => "?").join(",")}) ORDER BY at`)
    .all<{ at: number; entry: string }>(...keys)
  const journeyDoc = [GENERATED_NOTE, `# ${workspace} — journey`, "", ...journey.map((j) => `- ${new Date(j.at).toISOString().slice(0, 10)}: ${j.entry}`), ""].join(
    "\n",
  )
  for (const [name, content] of [
    ["INDEX.md", index],
    ["JOURNEY.md", journeyDoc],
  ] as const) {
    const rel = `${root}/${name}`
    db.prepare("UPDATE vault_outbox SET state = 'superseded' WHERE rel_path = ? AND state = 'pending'").run(rel)
    db.prepare("INSERT INTO vault_outbox(rel_path, topic_id, generation, content, hash, state, created_at) VALUES (?, NULL, NULL, ?, ?, 'pending', ?)").run(
      rel,
      content,
      sha256(content),
      now,
    )
  }
}

/** A stored vault path that would leave the vault (lexically or through a junction/symlink); never retried. */
export class VaultPathError extends Error {}

/**
 * Lexical containment of a stored relative path (rows restored from a backup may carry
 * anything): no absolute, drive-relative, UNC or `\\?\` path, no NUL, and never the root itself.
 */
function safeJoin(root: string, rel: string): string {
  if (isUncPath(root)) throw new VaultPathError("vault root cannot be a UNC or device path")
  if (!rel || rel.includes("\0") || isAbsolute(rel) || isUncPath(rel) || /^[a-zA-Z]:/.test(rel)) throw new VaultPathError(`vault path escapes root: ${rel}`)
  const base = resolve(root)
  const full = resolve(base, rel)
  if (isUncPath(base) || isUncPath(full) || full === base || !isInside(base, full)) throw new VaultPathError(`vault path escapes root: ${rel}`)
  return full
}

/**
 * The target (or its nearest existing ancestor) must really be inside the real vault root
 * (symlinks and junctions resolved); throws VaultPathError otherwise. False when the root
 * does not exist yet.
 */
function assertRealInside(root: string, target: string): boolean {
  const inside = realInside(root, target)
  if (inside === undefined) return false
  if (!inside) throw new VaultPathError(`vault path resolves outside the vault: ${relative(root, target).split(sep).join("/") || "."}`)
  return true
}

/**
 * Write through a fresh, exclusively created temp file in the checked directory, then rename
 * over the target (a symlink at the target is replaced, never written through). The temp
 * file is removed on any failure.
 */
function atomicWrite(root: string, path: string, content: string) {
  const dir = dirname(path)
  mkdirSync(root, { recursive: true })
  assertRealInside(root, dir)
  mkdirSync(dir, { recursive: true })
  assertRealInside(root, dir)
  const tmp = `${path}.om-tmp-${process.pid}-${randomBytes(6).toString("hex")}`
  try {
    writeFileSync(tmp, content, { flag: "wx" })
    renameSync(tmp, path)
  } catch (e) {
    try {
      unlinkSync(tmp)
    } catch {}
    throw e
  }
}

function openConflict(db: Database, topicId: string, relPath: string, generation: number | null, now: number) {
  db.prepare("UPDATE topics SET state = 'conflict', updated_at = ? WHERE id = ?").run(now, topicId)
  openReview(db, "vault-conflict", topicId, "the topic file was edited outside opencode-memory", { path: relPath, generation }, now)
}

export type MaterializeResult = { written: number; conflicts: number; failed: number }

export type MaterializeOptions = { log?: (level: "warn", msg: string, extra?: Record<string, unknown>) => void }

const RETRY_MS = 30_000
const RETRY_MAX_MS = 60 * 60_000

type OutboxRow = {
  id: number
  rel_path: string
  topic_id: string | null
  generation: number | null
  content: string
  hash: string
  force: number
  attempts: number | null
}

/** A topic file to read, only when it (a symlink resolved) really is inside the vault. */
function vaultFile(root: string, rel: string): string | undefined {
  try {
    const path = safeJoin(root, rel)
    return assertRealInside(root, path) ? path : undefined
  } catch {
    return undefined
  }
}

/** Unlink inside the vault; a missing file (or directory) counts as done. */
function removeFile(root: string, path: string) {
  if (!assertRealInside(root, dirname(path))) return
  try {
    unlinkSync(path)
  } catch (e) {
    if ((e as NodeJS.ErrnoException).code !== "ENOENT") throw e
  }
}

/** One outbox row; throws to be retried with backoff (VaultPathError: never retried). */
function materializeRow(db: Database, vaultDir: string, p: OutboxRow, now: number): "written" | "conflict" | "superseded" {
  const path = safeJoin(vaultDir, p.rel_path)
  if (!p.content) {
    removeFile(vaultDir, path)
    db.prepare("UPDATE vault_outbox SET state = 'written', written_at = ?, error = NULL WHERE id = ?").run(now, p.id)
    return "written"
  }
  if (db.prepare("SELECT 1 FROM vault_outbox WHERE rel_path = ? AND state = 'pending' AND content = '' AND id > ?").get(p.rel_path, p.id)) {
    db.prepare("UPDATE vault_outbox SET state = 'superseded' WHERE id = ?").run(p.id)
    return "superseded"
  }
  if (p.topic_id && !p.force && existsSync(path)) {
    const topic = db.prepare("SELECT * FROM topics WHERE id = ?").get<TopicRow>(p.topic_id)
    const readable = vaultFile(vaultDir, p.rel_path)
    const disk = parseFile(readable ? readFileSync(readable, "utf8") : "")
    const selfWritten = !!disk.fields.om_hash && disk.fields.om_hash === bodyHash(disk.body)
    const knownGeneration = topic?.materialized_generation == null || Number(disk.fields.om_generation) === topic.materialized_generation
    if (!selfWritten || !knownGeneration) {
      db.tx(() => {
        db.prepare("UPDATE vault_outbox SET state = 'conflict' WHERE id = ?").run(p.id)
        openConflict(db, p.topic_id!, p.rel_path, p.generation, now)
      })
      return "conflict"
    }
  }
  atomicWrite(vaultDir, path, p.content)
  db.tx(() => {
    db.prepare("UPDATE vault_outbox SET state = 'written', written_at = ?, error = NULL WHERE id = ?").run(now, p.id)
    if (p.topic_id) db.prepare("UPDATE topics SET materialized_hash = ?, materialized_generation = ? WHERE id = ?").run(p.hash, p.generation, p.topic_id)
  })
  return "written"
}

/**
 * Serialized vault writer (one lease across all instances). A file whose body no
 * longer matches the hash we wrote was edited externally: it is not overwritten
 * and a conflict review item is opened. Deletes run first (forgotten content must not
 * stay on disk); any row that fails (EBUSY/EPERM on Windows, a blocked path) stays
 * pending with backoff without holding up the others, and a row whose path is outside
 * the vault is failed permanently, never written or unlinked.
 */
export function materializeOutbox(db: Database, vaultDir: string, owner: string, now = Date.now(), opts: MaterializeOptions = {}): MaterializeResult {
  const res: MaterializeResult = { written: 0, conflicts: 0, failed: 0 }
  const claim = claimJob(db, "vault", "vault", owner, 60_000, now)
  if (!claim) return res
  try {
    const pending = db
      .prepare(
        "SELECT * FROM vault_outbox WHERE state = 'pending' AND (next_attempt_at IS NULL OR next_attempt_at <= ?) ORDER BY (content = '') DESC, id LIMIT 200",
      )
      .all<OutboxRow>(now)
    for (const p of pending) {
      if (!jobHeld(db, claim)) break
      try {
        const outcome = materializeRow(db, vaultDir, p, now)
        if (outcome === "written") res.written++
        else if (outcome === "conflict") res.conflicts++
      } catch (e) {
        const error = e instanceof VaultPathError ? e.message : `${(e as NodeJS.ErrnoException).code ?? "error"}: ${(e as Error)?.message ?? String(e)}`
        const what = p.content ? "write" : "delete"
        res.failed++
        if (e instanceof VaultPathError) {
          db.prepare("UPDATE vault_outbox SET state = 'failed', attempts = attempts + 1, next_attempt_at = NULL, error = ? WHERE id = ?").run(error, p.id)
          opts.log?.("warn", `vault ${what} of ${p.rel_path} refused: the path is outside the vault`, { error })
          continue
        }
        const attempts = (p.attempts ?? 0) + 1
        const delay = Math.min(RETRY_MAX_MS, RETRY_MS * 2 ** (attempts - 1))
        db.prepare("UPDATE vault_outbox SET attempts = ?, next_attempt_at = ?, error = ? WHERE id = ?").run(attempts, now + delay, error, p.id)
        opts.log?.("warn", `vault ${what} of ${p.rel_path} failed (attempt ${attempts}); retrying`, { error })
      }
    }
    db.prepare("DELETE FROM vault_outbox WHERE state IN ('written','superseded','failed') AND created_at < ?").run(now - 7 * 86_400_000)
    finishJob(db, claim, {}, now)
  } catch (e) {
    finishJob(db, claim, { error: String((e as Error).message), retryAfterMs: 30_000 }, now)
    throw e
  }
  return res
}

/** Detect topic files edited outside the plugin since they were last materialized. */
export function scanExternalEdits(db: Database, vaultDir: string, now = Date.now()): number {
  const topics = db.prepare("SELECT * FROM topics WHERE state = 'active' AND materialized_hash IS NOT NULL").all<TopicRow>()
  let found = 0
  for (const t of topics) {
    const path = vaultFile(vaultDir, t.rel_path)
    if (!path || !existsSync(path)) continue
    if (bodyHash(parseFile(readFileSync(path, "utf8")).body) === t.materialized_hash) continue
    db.tx(() => openConflict(db, t.id, t.rel_path, t.materialized_generation, now))
    found++
  }
  return found
}

/** Resolve a vault conflict. Importing the file is recorded as an external edit, never as human approval. */
export function resolveVaultConflict(
  db: Database,
  topicId: string,
  vaultDir: string,
  choice: "keep-file" | "overwrite",
  actor = "user",
  now = Date.now(),
): boolean {
  return db.tx(() => {
    const t = db.prepare("SELECT * FROM topics WHERE id = ?").get<TopicRow>(topicId)
    if (!t) return false
    if (choice === "keep-file") {
      const path = vaultFile(vaultDir, t.rel_path)
      const disk = path && existsSync(path) ? parseFile(readFileSync(path, "utf8")) : undefined
      if (disk) {
        const target = suppressionTarget(db, t.scope_key)
        const fallback = isSuppressed(db, t.title, target) ? forgottenTopicLabel(topicId) : t.title
        const body = sanitizeTopicBody(db, disk.body, target, fallback)
        const parsed = parseTopicBody(body)
        const title = parsed.title || fallback
        const generation = t.generation + 1
        db.prepare(
          "UPDATE topics SET title = ?, summary = ?, body = ?, generation = ?, content_hash = ?, approved = 0, state = 'active', updated_at = ? WHERE id = ?",
        ).run(title, parsed.summary, body, generation, contentHash(body), now, topicId)
        db.prepare("INSERT INTO topic_generations(topic_id, generation, title, body, hash, actor, created_at) VALUES (?,?,?,?,?,?,?)").run(
          topicId,
          generation,
          title,
          body,
          contentHash(body),
          "external-edit",
          now,
        )
      }
    } else {
      db.prepare("UPDATE topics SET state = 'active', updated_at = ? WHERE id = ?").run(now, topicId)
    }
    db.prepare("UPDATE vault_outbox SET state = 'superseded' WHERE topic_id = ? AND state = 'conflict'").run(topicId)
    db.prepare("UPDATE review_items SET state = 'approved', resolved_at = ?, resolved_by = ? WHERE ref_id = ? AND kind = 'vault-conflict' AND state = 'open'").run(
      now,
      actor,
      topicId,
    )
    enqueueTopic(db, topicId, now)
    db.prepare("UPDATE vault_outbox SET force = 1 WHERE topic_id = ? AND state = 'pending'").run(topicId)
    bumpMemoryGeneration(db)
    return true
  })
}

/** Human approval of a topic generation (only from the dashboard, never from agent tools). */
export function approveTopic(db: Database, topicId: string, now = Date.now()) {
  return db.tx(() => {
    const changed = db.prepare("UPDATE topics SET approved = 1, updated_at = ? WHERE id = ?").run(now, topicId).changes > 0
    if (changed) bumpMemoryGeneration(db)
    return changed
  })
}

/** Rollback re-sanitizes the old generation: it never restores suppressed or forgotten content. */
export function rollbackTopic(db: Database, topicId: string, generation: number, actor = "user", now = Date.now()) {
  return db.tx(() => {
    const t = db.prepare("SELECT * FROM topics WHERE id = ?").get<TopicRow>(topicId)
    const g = db.prepare("SELECT * FROM topic_generations WHERE topic_id = ? AND generation = ?").get<{ title: string; body: string }>(topicId, generation)
    if (!t || !g) return false
    const next = t.generation + 1
    const target = suppressionTarget(db, t.scope_key)
    const label = forgottenTopicLabel(topicId)
    const source = isSuppressed(db, g.title, target) ? g.body.replace(/^# .*$/m, `# ${label}`) : g.body
    const body = sanitizeTopicBody(db, source, target, label)
    const parsed = parseTopicBody(body)
    const title = parsed.title || label
    const slug = title === label ? forgottenTopicSlug(topicId) : t.slug
    const relPath = slug === t.slug ? t.rel_path : relPathWithSlug(t.rel_path, slug)
    if (relPath !== t.rel_path) enqueueVaultDelete(db, t.rel_path, now)
    db.prepare(
      "UPDATE topics SET slug = ?, rel_path = ?, title = ?, summary = ?, body = ?, generation = ?, content_hash = ?, approved = 0, updated_at = ? WHERE id = ?",
    ).run(slug, relPath, title, parsed.summary, body, next, contentHash(body), now, topicId)
    db.prepare("INSERT INTO topic_generations(topic_id, generation, title, body, hash, actor, created_at) VALUES (?,?,?,?,?,?,?)").run(
      topicId,
      next,
      title,
      body,
      contentHash(body),
      `rollback:${actor}`,
      now,
    )
    enqueueTopic(db, topicId, now)
    bumpMemoryGeneration(db)
    return true
  })
}

export function listTopics(db: Database, scopeKeys?: string[]) {
  return scopeKeys?.length
    ? db.prepare(`SELECT * FROM topics WHERE scope_key IN (${scopeKeys.map(() => "?").join(",")}) ORDER BY updated_at DESC`).all<TopicRow>(...scopeKeys)
    : db.prepare("SELECT * FROM topics ORDER BY updated_at DESC").all<TopicRow>()
}

export function topicGenerations(db: Database, topicId: string) {
  return db
    .prepare("SELECT topic_id, generation, title, hash, actor, created_at FROM topic_generations WHERE topic_id = ? ORDER BY generation DESC")
    .all<any>(topicId)
}
